CREATE TABLE BEADLE_PROTECH_CALL_LOG (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    AT                          TIMESTAMP       NOT NULL,
    USER_NAME                   VARCHAR2(200),
    CORRELATION_ID              VARCHAR2(100),
    SYSTEM                      VARCHAR2(20)    NOT NULL,
    OPERATION                   VARCHAR2(100)   NOT NULL,
    TARGET                      VARCHAR2(500),
    OUTCOME                     VARCHAR2(10)    NOT NULL,
    MESSAGE                     VARCHAR2(2000),
    DURATION_MS                 NUMBER(19)      NOT NULL,
    CONSTRAINT PK_BEADLE_PROTECH_CALL_LOG PRIMARY KEY (ID),
    CONSTRAINT CK_BEADLE_PROTECH_CALL_LOG_SYSTEM CHECK (SYSTEM IN ('PROTECH', 'GUI')),
    CONSTRAINT CK_BEADLE_PROTECH_CALL_LOG_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILURE'))
);
CREATE INDEX IX_BEADLE_PROTECH_CALL_LOG_AT ON BEADLE_PROTECH_CALL_LOG (AT);
CREATE INDEX IX_BEADLE_PROTECH_CALL_LOG_CORRELATION ON BEADLE_PROTECH_CALL_LOG (CORRELATION_ID);
