CREATE TABLE BEADLE_PROTECH_CHANGE (
    CHANGE_NUMBER               VARCHAR2(40)    NOT NULL,
    STATE                       VARCHAR2(30),
    LAST_SEEN_AT                TIMESTAMP,
    LAST_EVENT_AT               TIMESTAMP,
    CORRELATION_ID              VARCHAR2(100),
    CONSTRAINT PK_BEADLE_PROTECH_CHANGE PRIMARY KEY (CHANGE_NUMBER),
    CONSTRAINT CK_BEADLE_PROTECH_CHANGE_STATE CHECK (STATE IN ('DRAFT', 'BUSINESS_APPROVAL', 'PRIMARY_APPROVAL',
        'SECONDARY_APPROVAL', 'SUPPORT_APPROVAL', 'CTASK_APPROVAL', 'ESCALATED_APPROVAL', 'IMPLEMENTATION', 'CLOSED'))
);
CREATE INDEX IX_BEADLE_PROTECH_CHANGE_STATE ON BEADLE_PROTECH_CHANGE (STATE);
